"""Keep every file small enough for an agent to read in one go.

Limit: 5,000 tokens per file, estimated as bytes / 4. Idea from Matt Pocock (October 2026):
"Create a pre-commit hook that prevents files over 5,000 tokens... Provide explicit instructions on
how to split files in the error message."

Usage:
  check_file_tokens.py FILE...   check these files (the pre-commit hook passes staged files)
  check_file_tokens.py --all     check every tracked or new, non-ignored file (./gradlew check and CI)
"""

from __future__ import annotations

import fnmatch
import subprocess
import sys
from pathlib import Path

MAX_TOKENS = 5_000
BYTES_PER_TOKEN = 4

# Files agents don't author: generated, vendored, or tool-owned. They can be any size.
IGNORED = [
    "docs/modules/*",  # generated by ModularityTests
    "gradle/wrapper/*",
    "gradlew",
    "gradlew.bat",
    "gradle/verification-metadata.xml",
    "*.lockfile",
    "LICENSE*",
    ".agents/skills/*",  # vendored from mattpocock/skills; updated by script, not by agents
]

HOW_TO_SPLIT = {
    "main-java": (
        "Split it along a responsibility. Move a cohesive group of methods, and the state only they use, "
        "into a new package-private class in the same package, and have this class delegate to it. "
        "Keep the module's public API types small (see the codebase-design skill)."
    ),
    "test-java": (
        "Split the tests by the behaviour they cover into separate test classes, one behaviour per class. "
        "Move shared setup into a small fixture or helper class in the same package."
    ),
    "markdown": (
        "Split it by topic into separate files and link to them from this one, so readers load only the "
        "part they need (progressive disclosure, see the writing-for-agents skill)."
    ),
    "other": "Split it into smaller files that each do one thing, and reference them from where this one is used.",
}


def kind(path: str) -> str:
    if path.endswith(".java"):
        return "test-java" if "/src/test/" in path else "main-java"
    if path.endswith(".md"):
        return "markdown"
    return "other"


def is_ignored(path: str) -> bool:
    return any(fnmatch.fnmatch(path, pattern) for pattern in IGNORED)


def is_binary(data: bytes) -> bool:
    return b"\0" in data[:8000]


def violations(paths: list[str], root: Path) -> list[str]:
    errors = []
    for path in paths:
        file = root / path
        if is_ignored(path) or not file.is_file():
            continue
        data = file.read_bytes()
        if is_binary(data):
            continue
        tokens = len(data) // BYTES_PER_TOKEN
        if tokens > MAX_TOKENS:
            errors.append(
                f"{path} is ~{tokens:,} tokens (limit {MAX_TOKENS:,}, counted as bytes/4).\n"
                f"  {HOW_TO_SPLIT[kind(path)]}"
            )
    return errors


def main(args: list[str]) -> int:
    root = Path(subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True).stdout.strip())
    if args == ["--all"]:
        paths = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=root, capture_output=True, text=True, check=True).stdout.split()
    else:
        paths = args
    errors = violations(paths, root)
    for error in errors:
        print(error, file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
