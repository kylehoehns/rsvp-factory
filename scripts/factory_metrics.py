"""Write docs/factory/metrics.md: how the factory's PRs fared, and what the maintainer did with them.

Usage: python3 scripts/factory_metrics.py   (needs gh, signed in; reads .factory/runs/metrics.jsonl if present)

Outcomes, not activity (practice 18): merged or not, rounds needed, time to merge, reverts, and whether the
maintainer changed a PR before merging it. "Tier vs maintainer" is the agreement data auto-merge waits for
(docs/adr/0006-auto-merge-low-risk-in-stages.md).
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True).stdout.strip())
REPO = "kylehoehns/rsvp-factory"
MAINTAINERS = {"kylehoehns"}
PREFIX = "agent/issue-"


def gh_json(*args: str) -> list | dict:
    out = subprocess.run(["gh", *args, "--repo", REPO], capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def hours(start: str, end: str | None) -> float | None:
    if not end:
        return None
    parse = lambda s: datetime.fromisoformat(s.replace("Z", "+00:00"))
    return round((parse(end) - parse(start)).total_seconds() / 3600, 1)


def maintainer_action(pr: dict) -> str:
    if pr["state"] == "OPEN":
        return "open"
    if pr["state"] == "CLOSED":
        return "closed unmerged"
    # Agent commits are authored by the factory's bot user (rsvp-factory-bot until factory-kit, then kh-factory-bot; or, before 2026-10-22, by the maintainer with Claude
    # as co-author); a commit with neither is a human change.
    agents = {"kh-factory-bot[bot]", "rsvp-factory-bot[bot]", "claude"}
    logins = [{a.get("login") for a in c.get("authors", [])} for c in pr["commits"]]
    human = any(authors & MAINTAINERS and not authors & agents for authors in logins)
    return "merged after changes" if human else "merged as-is"


def describe(pr: dict, reverted: set[int]) -> dict:
    comments = "\n".join(c["body"] for c in pr["comments"])
    review_rounds = [int(n) for n in re.findall(r"factory-review-round source=\S+ blockers=(\d+)", comments)]
    filed = re.findall(r"Filed follow-ups: (.*)", comments)
    return {
        "pr": pr["number"],
        "ticket": int(pr["headRefName"][len(PREFIX):]),
        "tier": next((l["name"][5:] for l in pr["labels"] if l["name"].startswith("risk:")), "?"),
        "lines": pr["additions"] + pr["deletions"],
        "ci_rounds": len(re.findall(r"factory-ci-round sha=", comments)),
        "review_rounds": sum(1 for n in review_rounds if n > 0),
        "follow_ups": len(re.findall(r"#\d+", filed[0])) if filed else 0,
        "decision_needed": any(l["name"] == "decision-needed" for l in pr["labels"]),
        "action": maintainer_action(pr),
        "hours_to_merge": hours(pr["createdAt"], pr["mergedAt"]),
        "reverted": pr["number"] in reverted,
    }


def reverted_prs() -> set[int]:
    log = subprocess.run(["git", "log", "origin/main", "--grep=^Revert", "--format=%s%n%b"], cwd=ROOT,
                         capture_output=True, text=True).stdout
    return {int(n) for n in re.findall(r"#(\d+)", log)}


def usage_by_ticket() -> dict[int, dict]:
    path = ROOT / ".factory/runs/metrics.jsonl"
    totals: dict[int, dict] = defaultdict(lambda: Counter())
    if path.exists():
        for line in path.read_text().splitlines():
            run = json.loads(line)
            t = totals[run["issue"]]
            t["sessions"] += 1
            t["minutes"] += run["minutes"]
            for key, value in run["tokens"].items():
                t[key] += value
    return totals


def median(values: list[float]) -> str:
    values = sorted(v for v in values if v is not None)
    return f"{values[len(values) // 2]}" if values else "n/a"


def report(rows: list[dict], usage: dict[int, dict]) -> str:
    merged = [r for r in rows if r["action"].startswith("merged")]
    tiers = Counter((r["tier"], r["action"]) for r in rows)
    lines = [
        "# Factory metrics",
        "",
        f"*Generated by `scripts/factory_metrics.py` on {datetime.now().date()}. Factory PRs only (`{PREFIX}*` branches).*",
        "",
        "## Summary",
        "",
        f"- PRs opened: {len(rows)}; merged: {len(merged)}; merged as-is: {sum(r['action'] == 'merged as-is' for r in rows)}; "
        f"closed unmerged: {sum(r['action'] == 'closed unmerged' for r in rows)}; reverted: {sum(r['reverted'] for r in rows)}",
        f"- Median hours from PR to merge: {median([r['hours_to_merge'] for r in merged])}",
        f"- Median PR size (lines changed): {median([r['lines'] for r in rows])}",
        f"- PRs that needed CI fix rounds: {sum(r['ci_rounds'] > 0 for r in rows)}; review fix rounds: {sum(r['review_rounds'] > 0 for r in rows)}",
        f"- Follow-up tickets filed: {sum(r['follow_ups'] for r in rows)}; PRs with decisions for the maintainer: {sum(r['decision_needed'] for r in rows)}",
        "",
        "## Risk tier vs what the maintainer did",
        "",
        "Auto-merge for the low tier waits until low-tier PRs are reliably merged as-is (ADR 0006).",
        "",
        "| Tier | Merged as-is | Merged after changes | Closed unmerged | Open |",
        "|---|---|---|---|---|",
        *[f"| {t} | {tiers[(t, 'merged as-is')]} | {tiers[(t, 'merged after changes')]} | {tiers[(t, 'closed unmerged')]} | {tiers[(t, 'open')]} |"
          for t in ["low", "medium", "high"]],
        "",
        "## Pull requests",
        "",
        "| PR | Ticket | Tier | Lines | CI rounds | Review rounds | Follow-ups | Outcome | Hours to merge | Agent sessions | Output tokens |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda r: r["pr"]):
        u = usage.get(r["ticket"], {})
        outcome = r["action"] + (" (reverted)" if r["reverted"] else "")
        lines.append(f"| #{r['pr']} | #{r['ticket']} | {r['tier']} | {r['lines']} | {r['ci_rounds']} | {r['review_rounds']} | "
                     f"{r['follow_ups']} | {outcome} | {r['hours_to_merge'] if r['hours_to_merge'] is not None else ''} | "
                     f"{u.get('sessions', '')} | {u.get('output', '')} |")
    lines += ["", "Agent sessions and tokens come from the maintainer's local run log, so PRs from before it existed show none. "
              "Tokens count against a subscription, so they're shown as tokens, not dollars."]
    return "\n".join(lines) + "\n"


def main() -> int:
    listed = gh_json("pr", "list", "--state", "all", "--limit", "200", "--json", "number,headRefName")
    reverted = reverted_prs()
    rows = []
    for item in (p for p in listed if p["headRefName"].startswith(PREFIX)):
        # One PR at a time: asking for every PR's commits and comments at once exceeds GitHub's query limit.
        rows.append(describe(gh_json("pr", "view", str(item["number"]), "--json",
                                     "number,headRefName,state,createdAt,mergedAt,additions,deletions,labels,commits,comments"), reverted))
    out = ROOT / "docs/factory/metrics.md"
    out.write_text(report(rows, usage_by_ticket()))
    print(f"Wrote {out.relative_to(ROOT)} ({len(rows)} factory PRs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
